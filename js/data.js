  /* ---------- 运行时：真实数据 + 接口刷新 + 快照兜底 ---------- */
  var API = 'https://api.worldbank.org/v2';
  var EXP = 'NE.EXP.GNFS.CD';
  var IMP = 'NE.IMP.GNFS.CD';
  var CACHE_KEY = 'trade.worldbank.v2';
  var CACHE_TTL = 7 * 24 * 3600 * 1000;
  var NONE = YEARS.map(function () { return null; });

  var ISO2ID = {};
  Object.keys(NAMES).forEach(function (iso) { ISO2ID[iso] = NAMES[iso][0]; });

  var table = {};
  Object.keys(NAMES).forEach(function (iso) {
    var m = NAMES[iso];
    table[iso] = {
      c: m[1], n: m[2], id: m[0], p: m[3] == null ? null : [m[3], m[4]],
      x: NONE, m: NONE
    };
  });
  Object.keys(SNAP).forEach(function (iso) {
    if (!table[iso]) return;
    table[iso].x = SNAP[iso].x;
    table[iso].m = SNAP[iso].m;
  });

  function loadCache() {
    try {
      var raw = localStorage.getItem(CACHE_KEY);
      if (!raw) return false;
      var o = JSON.parse(raw);
      if (!o || !o.d || Date.now() - o.t > CACHE_TTL) return false;
      Object.keys(o.d).forEach(function (k) {
        if (!table[k]) return;
        table[k].x = o.d[k].x;
        table[k].m = o.d[k].m;
        probed[k] = true;
      });
      return !!Object.keys(o.d).length;
    } catch (e) { return false; }
  }

  function saveCache() {
    try {
      var d = {};
      Object.keys(dirty).forEach(function (k) { d[k] = { x: table[k].x, m: table[k].m }; });
      if (!Object.keys(d).length) return;
      var prev;
      try { prev = JSON.parse(localStorage.getItem(CACHE_KEY)); } catch (e) { prev = null; }
      if (prev && prev.d) Object.keys(prev.d).forEach(function (k) { if (!d[k]) d[k] = prev.d[k]; });
      localStorage.setItem(CACHE_KEY, JSON.stringify({ t: Date.now(), d: d }));
    } catch (e) { /* 隐私模式或配额异常时静默降级到内嵌快照 */ }
  }

  /* probed: 已经问过接口，不再重复请求；dirty: 需要写进本地缓存 */
  var inflight = {}, probed = {}, dirty = {};

  function toArr(rows) {
    var arr = YEARS.map(function () { return null; });
    rows.forEach(function (r) {
      if (r.value == null) return;
      var i = YEARS.indexOf(r.date);
      if (i >= 0) arr[i] = Math.round(r.value / 1e7) / 10;   // 现价美元 -> 亿美元
    });
    return arr;
  }

  function fetchInd(iso, ind) {
    return fetch(API + '/country/' + iso + '/indicator/' + ind
        + '?date=' + YEARS[0] + ':' + YEARS[YEARS.length - 1] + '&format=json&per_page=100')
      .then(function (r) { if (!r.ok) throw new Error('http ' + r.status); return r.json(); })
      .then(function (j) {
        /* 接口出错时同样返回 200 + [{message:[…]}]，必须显式识别 */
        if (!j || !Array.isArray(j[1])) throw new Error('bad payload');
        return toArr(j[1]);
      });
  }

  function refresh(iso) {
    var e = table[iso];
    if (!e || inflight[iso]) return inflight[iso] || Promise.resolve(null);
    inflight[iso] = Promise.all([fetchInd(iso, EXP), fetchInd(iso, IMP)])
      .then(function (arr) {
        var got = arr[0].some(function (v) { return v != null; })
               || arr[1].some(function (v) { return v != null; });
        if (got) { e.x = arr[0]; e.m = arr[1]; dirty[iso] = true; }
        probed[iso] = true;
        saveCache();
        delete inflight[iso];
        return e;
      })
      .catch(function () { delete inflight[iso]; return null; });
    return inflight[iso];
  }

  /* 批量刷新：一次请求拿回多个经济体，避免逐个串行等待 */
  function applyRows(rows, key) {
    var by = {};
    rows.forEach(function (r) {
      if (r.value == null) return;
      var iso = r.countryiso3code, i = YEARS.indexOf(r.date);
      if (i < 0 || !table[iso]) return;
      if (!by[iso]) by[iso] = YEARS.map(function () { return null; });
      by[iso][i] = Math.round(r.value / 1e7) / 10;
    });
    Object.keys(by).forEach(function (iso) {
      table[iso][key] = by[iso];
      dirty[iso] = true;
      probed[iso] = true;
    });
    return by;
  }

  function fetchMany(list, ind, key) {
    return fetch(API + '/country/' + list.join(';') + '/indicator/' + ind
        + '?date=' + YEARS[0] + ':' + YEARS[YEARS.length - 1] + '&format=json&per_page=500')
      .then(function (r) { if (!r.ok) throw new Error('http ' + r.status); return r.json(); })
      .then(function (j) {
        if (!j || !Array.isArray(j[1])) throw new Error('bad payload');
        return applyRows(j[1], key);
      });
  }

  function refreshMany(list) {
    return Promise.all([fetchMany(list, EXP, 'x'), fetchMany(list, IMP, 'm')])
      .then(function (res) {
        saveCache();
        return Object.keys(res[0]).filter(function (iso) { return res[1][iso]; });
      })
      .catch(function () { return []; });
  }

  function latestIndex(e) {
    for (var i = YEARS.length - 1; i > 0; i--) {
      if (e.x[i] != null && e.m[i] != null && e.x[i - 1] != null && e.m[i - 1] != null) return i;
    }
    for (var j = YEARS.length - 1; j >= 0; j--) if (e.x[j] != null || e.m[j] != null) return j;
    return -1;
  }

  /* 一个国家在面板上需要的全部数字 */
  function stats(iso) {
    var e = table[iso];
    if (!e) return null;
    var base = { cn: e.c, en: e.n, id: e.id, iso: iso, ll: e.p };
    var i = latestIndex(e);
    if (i < 0) { base.nodata = true; return base; }
    var cur = (e.x[i] || 0) + (e.m[i] || 0);
    var yoy = null;
    if (i > 0 && e.x[i - 1] != null && e.m[i - 1] != null) {
      var pt = (e.x[i - 1] || 0) + (e.m[i - 1] || 0);
      if (pt) yoy = (cur - pt) / pt * 100;
    }
    var cn = table.CHN, hist = [];
    for (var y = Math.max(0, i - 3); y <= i; y++) {
      var t = (e.x[y] || 0) + (e.m[y] || 0);
      if (!t) continue;
      var ct = cn ? (cn.x[y] || 0) + (cn.m[y] || 0) : 0;
      hist.push({ y: +YEARS[y], amt: t, pct: ct ? t / ct * 100 : 0 });
    }
    base.exp = e.x[i] || 0;
    base.imp = e.m[i] || 0;
    base.total = cur;
    base.year = +YEARS[i];
    base.yoy = yoy;
    base.hist = hist;
    return base;
  }

  /* 全球排名：出口 / 进口 / 进出口总额，单位亿美元（不含中国，中国是基准） */
  function ranking(key) {
    var pick = key === 'import' ? 'm' : key === 'export' ? 'x' : null;
    var rows = [];
    Object.keys(table).forEach(function (iso) {
      if (iso === 'CHN') return;
      var e = table[iso], i = latestIndex(e);
      if (i < 0) return;
      var v = pick ? (e[pick][i] || 0) : (e.x[i] || 0) + (e.m[i] || 0);
      if (v > 0) rows.push({ iso: iso, cn: e.c, val: v });
    });
    rows.sort(function (a, b) { return b.val - a.val; });
    return rows;
  }

